"""Small, site-bound, persistent media jobs and byte assets (PostgreSQL or SQLite).

The generated bytes never enter BuildPlan JSON, WordPress snapshots, or tokens.
"""
from __future__ import annotations

import json
import uuid
from datetime import datetime, timedelta, timezone
from typing import Any
from sqlalchemy import MetaData, Table, Column, String, LargeBinary, DateTime, Text, select, func, delete, UniqueConstraint
from sqlalchemy.exc import IntegrityError

META = MetaData()
JOBS = Table("thesis_media_jobs", META,
    Column("job_id", String(48), primary_key=True),
    Column("plan_id", String(48), nullable=False),
    Column("site_id", String(64), nullable=False),
    Column("status", String(32), nullable=False),
    Column("created_at", DateTime(timezone=True), nullable=False),
    Column("payload", Text, nullable=False),
    UniqueConstraint("site_id", "plan_id", name="uq_thesis_media_plan_per_site"))
ASSETS = Table("thesis_media_assets", META,
    Column("job_id", String(48), primary_key=True),
    Column("key", String(32), primary_key=True),
    Column("site_id", String(64), nullable=False),
    Column("image_bytes", LargeBinary, nullable=False))


def now(): return datetime.now(timezone.utc)

class MediaStore:
    def __init__(self, engine):
        self.engine = engine
        META.create_all(engine)

    def get_by_plan(self, site_id: str, plan_id: str) -> dict[str, Any] | None:
        with self.engine.connect() as db:
            row = db.execute(select(JOBS).where(JOBS.c.site_id == site_id, JOBS.c.plan_id == plan_id)).mappings().first()
        return self._unpack(row)

    @staticmethod
    def _unpack(row):
        if row is None: return None
        return {**json.loads(row["payload"]), "job_id": row["job_id"], "site_id": row["site_id"],
                "plan_id": row["plan_id"], "status": row["status"]}

    def get(self, site_id: str, job_id: str) -> dict[str, Any] | None:
        with self.engine.connect() as db:
            row = db.execute(select(JOBS).where(JOBS.c.site_id == site_id, JOBS.c.job_id == job_id)).mappings().first()
        return self._unpack(row)

    def count_today(self, site_id: str) -> int:
        start = now().replace(hour=0, minute=0, second=0, microsecond=0)
        with self.engine.connect() as db:
            return int(db.execute(select(func.count()).select_from(JOBS).where(
                JOBS.c.site_id == site_id, JOBS.c.created_at >= start)).scalar_one())

    def create(self, site_id: str, plan_id: str, specs: list[dict[str, Any]]) -> dict[str, Any]:
        existing = self.get_by_plan(site_id, plan_id)
        if existing: return {**existing, "_created_here": False}
        job_id = str(uuid.uuid4())
        obj = {"job_id": job_id, "site_id": site_id, "plan_id": plan_id, "status": "queued",
               "assets": [{"key": s["key"], "role": s["role"], "alt": s["alt"],
                           "provenance": s["provenance"]} for s in specs], "error": ""}
        try:
            with self.engine.begin() as db:
                db.execute(JOBS.insert().values(job_id=job_id, site_id=site_id, plan_id=plan_id,
                    status="queued", created_at=now(), payload=json.dumps({k:v for k,v in obj.items() if k not in ("job_id","site_id","plan_id","status")}, ensure_ascii=False)))
        except IntegrityError:
            other = self.get_by_plan(site_id, plan_id)
            if other: return {**other, "_created_here": False}
            raise
        return {**obj, "_created_here": True}

    def update(self, site_id: str, job_id: str, **changes):
        job = self.get(site_id, job_id)
        if not job: raise ValueError("Unknown media job")
        job.update(changes)
        from sqlalchemy import update
        with self.engine.begin() as db:
            db.execute(update(JOBS).where(JOBS.c.site_id == site_id, JOBS.c.job_id == job_id).values(
                status=job["status"], payload=json.dumps({k:v for k,v in job.items() if k not in ("job_id","site_id","plan_id","status")}, ensure_ascii=False)))

    def save_asset(self, site_id: str, job_id: str, key: str, data: bytes):
        with self.engine.begin() as db:
            db.execute(ASSETS.insert().values(site_id=site_id, job_id=job_id, key=key, image_bytes=data))

    def asset(self, site_id: str, job_id: str, key: str) -> bytes | None:
        with self.engine.connect() as db:
            return db.execute(select(ASSETS.c.image_bytes).where(ASSETS.c.site_id == site_id,
                ASSETS.c.job_id == job_id, ASSETS.c.key == key)).scalar_one_or_none()

    def cleanup(self, days: int = 2):
        cutoff = now() - timedelta(days=days)
        with self.engine.begin() as db:
            old = [r[0] for r in db.execute(select(JOBS.c.job_id).where(JOBS.c.created_at < cutoff))]
            if old:
                db.execute(delete(ASSETS).where(ASSETS.c.job_id.in_(old)))
                db.execute(delete(JOBS).where(JOBS.c.job_id.in_(old)))
